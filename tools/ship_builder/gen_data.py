"""Write scripts/ship_types.gd from specs.DATA so the game data and the models never drift apart.
Run after build_all.py: python gen_data.py"""
import os, math
import specs

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'scripts', 'ship_types.gd')

def gd(v, ind=0):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, float):
        if abs(v - math.pi) < 1e-9:
            return 'PI'
        if abs(v + math.pi) < 1e-9:
            return '-PI'
        if abs(v - math.pi / 2) < 1e-9:
            return 'PI / 2'
        if abs(v + math.pi / 2) < 1e-9:
            return '-PI / 2'
        return repr(float(v))
    if isinstance(v, str):
        return '"%s"' % v.replace('"', '\\"')
    if isinstance(v, (list, tuple)):
        return '[' + ', '.join(gd(x, ind) for x in v) + ']'
    if isinstance(v, dict):
        return '{' + ', '.join('%s: %s' % (gd(k), gd(x, ind)) for k, x in v.items()) + '}'
    raise TypeError(type(v))

lines = ['class_name ShipTypes', '## GENERATED by tools/ship_builder/gen_data.py from specs.py. Do not edit by hand: change specs.py and rerun.',
         '## Ship classes built with the parametric warship builder (see Data.TYPES for the hand-built ones).', '', 'const TYPES := {']
for name, d in specs.DATA.items():
    d = dict(d)
    d['models'] = {'m21': 'res://assets/models/%s.glb' % name, 'm22': 'res://assets/models/%s.glb' % name}
    d.setdefault('role', 'warship')
    lines.append('\t"%s": {' % name)
    for k, v in d.items():
        lines.append('\t\t"%s": %s,' % (k, gd(v)))
    lines.append('\t},')
lines.append('}')
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', OUT, len(specs.DATA), 'classes')
